async function seedSocialMediaData() {
    console.log('\n╔══════════════════════════════════════════════════════════════╗');
    console.log('║        VedEngine Social Media Database Seeder              ║');
    console.log('╚══════════════════════════════════════════════════════════════╝');

    let inserted = 0;
    let updated = 0;
    let failed = 0;

    for (const entry of SOCIAL_MEDIA_DATA) {
        try {
            const existing = await prisma.document.findFirst({
                where: { title: entry.title },
                select: { id: true, url: true },
            });

            if (existing) {
                await prisma.document.update({
                    where: { id: existing.id },
                    data: { url: entry.url },
                });
                console.log(`  🔄 Updated URL: ${entry.title} -> ${entry.url}`);
                updated++;
                continue;
            }

            await prisma.document.create({
                data: {
                    title: entry.title,
                    content: entry.content,
                    description: entry.description,
                    url: entry.url,
                    fileType: 'WEB',
                },
            });

            console.log(`  ✅ Indexed: ${entry.title}`);
            inserted++;
        } catch (error) {
            console.error(`  ❌ Failed: ${entry.title} - ${error.message}`);
            failed++;
        }
    }

    console.log('\n╔══════════════════════════════════════════════════════════════╗');
    console.log('║                    SEEDING COMPLETE                         ║');
    console.log('╚══════════════════════════════════════════════════════════════╝');
    console.log(`\n📊 Results:`);
    console.log(`   ✅ Inserted:  ${inserted}`);
    console.log(`   🔄 Updated:   ${updated}`);
    console.log(`   ❌ Failed:    ${failed}`);
    console.log(`   📦 Total:     ${SOCIAL_MEDIA_DATA.length}`);

    await prisma.$disconnect();
}

seedSocialMediaData().catch((err) => {
    console.error('💥 Seeder crashed:', err);
    prisma.$disconnect();
    process.exit(1);
});